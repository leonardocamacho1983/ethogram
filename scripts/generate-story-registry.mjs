import { readdir, writeFile } from 'node:fs/promises'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const ignoredDirectories = new Set([
  '.git',
  '.next',
  'node_modules',
  'coverage',
  'dist',
  'out',
])

export async function discoverStoryFiles(rootDirectory) {
  const storyFiles = []

  async function visit(directory) {
    const entries = await readdir(directory, { withFileTypes: true })
    entries.sort((left, right) => left.name.localeCompare(right.name))

    for (const entry of entries) {
      if (entry.isDirectory() && ignoredDirectories.has(entry.name)) continue

      const absolutePath = path.join(directory, entry.name)
      if (entry.isDirectory()) {
        await visit(absolutePath)
      } else if (entry.isFile() && entry.name.endsWith('.agent.stories.ts')) {
        storyFiles.push(absolutePath)
      }
    }
  }

  await visit(rootDirectory)
  return storyFiles
}

export function renderRegistry(storyFiles, registryPath) {
  const registryDirectory = path.dirname(registryPath)
  const imports = storyFiles.map((storyFile, index) => {
    let importPath = path.relative(registryDirectory, storyFile)
      .replaceAll(path.sep, '/')
      .replace(/\.ts$/, '')
    if (!importPath.startsWith('.')) importPath = `./${importPath}`
    return `import * as storyModule${index} from '${importPath}'`
  })
  const moduleNames = storyFiles.map((_, index) => `storyModule${index}`)
  const projectRoot = path.dirname(path.dirname(registryDirectory))
  const moduleFiles = storyFiles.map((storyFile) =>
    path.relative(projectRoot, storyFile).replaceAll(path.sep, '/'),
  )

  return [
    '// Generated by scripts/generate-story-registry.mjs. Do not edit.',
    ...imports,
    '',
    `export const storyModules = [${moduleNames.join(', ')}]`,
    `export const storyModuleFiles = ${JSON.stringify(moduleFiles)}`,
    '',
  ].join('\n')
}

export async function generateRegistry({ rootDirectory, registryPath }) {
  const storyFiles = await discoverStoryFiles(rootDirectory)
  const registry = renderRegistry(storyFiles, registryPath)
  await writeFile(registryPath, registry, 'utf8')
  return storyFiles
}

const scriptPath = fileURLToPath(import.meta.url)
const invokedPath = process.argv[1] ? path.resolve(process.argv[1]) : ''

if (scriptPath === invokedPath) {
  const rootDirectory = process.cwd()
  const registryPath = path.join(
    rootDirectory,
    'lib/agentbook/generated-story-registry.ts',
  )
  const storyFiles = await generateRegistry({ rootDirectory, registryPath })
  console.log(`Discovered ${storyFiles.length} Agentbook Story file(s).`)
}
